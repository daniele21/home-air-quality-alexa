#!/usr/bin/env python3
"""Airwise synthetic-only local UI fixture HTTP server for screenshot reviews.

All numbers/activities are hard-coded DEMO values generated by math functions.
No credentials, device ID, DB, user location, internet, or Amazon API access.
Only binds 127.0.0.1 to serve the immutable source HTML.
"""
from __future__ import annotations
from datetime import datetime,timedelta,date,timezone
from http.server import BaseHTTPRequestHandler,ThreadingHTTPServer
from pathlib import Path
from urllib.parse import urlparse,parse_qs
import math,json,sys,os

ROOT=Path(__file__).resolve().parents[1]/"src/home_air_quality_alexa"
END=datetime(2026,11,1,tzinfo=timezone.utc)
START=END-timedelta(days=30)
NAMES={"PM25":("PM2.5","µg/m³"),"VOC":("VOC","indice"),"CO":("CO","ppm"),"Humidity":("Umidità","%"),"Air Quality":("Indice Alexa","indice")}

def series(key,i):
    h=i%24
    if key=="PM25":
        return round(10+3*math.sin(i*.13)+2*math.sin(h*math.pi/12)+ (19 if i%149 in (15,16,17) else 0),1)
    if key=="VOC": return round(28+12*math.cos(i*.12),1)
    if key=="CO": return round(max(0,0.5+0.3*math.sin(i*.21)),2)
    if key=="Humidity": return round(51+8*math.cos(i*.035),1)
    return round(30+7*math.sin(i*.08),1)

def mean(seq):
    seq=[v for v in seq if v is not None]
    return round(sum(seq)/len(seq),2) if seq else None

def data(days,offset=0):
    end=END-timedelta(days=offset);start=end-timedelta(days=days)
    start_idx=int((start-START).total_seconds()/3600)
    allch=[]
    for key,(label,unit) in NAMES.items():
        vals=[series(key,start_idx+i) for i in range(days*24)]
        hourly=[{"timestamp_utc":(start+timedelta(hours=i)).isoformat(),"value":v} for i,v in enumerate(vals)]
        daily=[{"day_utc":(start+timedelta(days=i)).date().isoformat(),"mean":mean(vals[i*24:(i+1)*24]),"hours":24} for i in range(days)]
        previous_daily=[{"day_utc":(start-timedelta(days=days-i)).date().isoformat(),"mean":mean([series(key,start_idx-days*24+i*24+j) for j in range(24)]),"hours":24} for i in range(days)]
        previous=mean([d["mean"] for d in previous_daily])
        avg=mean(vals)
        allch.append({"key":key,"label":label,"unit":unit,
            "summary":{"mean":avg,"minimum":min(vals),"maximum":max(vals),"coverage_pct":100,"observed_hours":days*24,"expected_hours":days*24},
            "previous":{"mean":previous,"observed_hours":days*24},
            "comparison_pct":round((avg/previous-1)*100,1) if previous else None,
            "daily":daily,"previous_daily":previous_daily,"hourly":hourly})
    return {"schema_version":"1","timezone":"UTC","days":days,"start_date_utc":start.date().isoformat(),
      "end_date_utc_exclusive":end.date().isoformat(),"latest_available_hour_utc":(end-timedelta(hours=1)).isoformat(),"channels":allch}

def pollution(days,offset=0):
    d=data(days,offset)
    start=datetime.fromisoformat(d["start_date_utc"]).replace(tzinfo=timezone.utc)
    vals=[series("PM25", int((start-START).total_seconds()/3600)+i) for i in range(days*24)]
    daily=[]
    for i in range(days):
        dv=vals[i*24:(i+1)*24]
        avg=mean(dv)
        daily.append({"date_utc":(start+timedelta(days=i)).date().isoformat(),"mean":avg,"maximum_hourly":max(dv),"hours":24,
         "complete_enough_for_24h_comparison":True,"above_who_ambient_reference":avg>15})
    diurnal={};weekday={};heat={}
    for key in NAMES:
        diurnal[key]=[{"hour_local":h,"mean":round(series(key,h),1),"sample_count":days} for h in range(24)]
        weekday[key]=[{"weekday_local":w,"mean":round(series(key,w*14+20),1),"sample_count":days*3} for w in range(7)]
        heat[key]=[[{"weekday_local":w,"hour_local":h,
           "mean":round(series(key,w*17+h),1),"sample_count":days//7+1} for h in range(24)] for w in range(7)]
    event_day=start+timedelta(days=max(2,days//3))
    episodes=[{"start_utc":event_day.isoformat(),"end_utc_exclusive":(event_day+timedelta(hours=3)).isoformat(),
      "duration_hours":3,"peak":29.5,"mean":26.1,"excess_above_relative_p90":21.3},
      {"start_utc":(event_day+timedelta(days=4)).isoformat(),"end_utc_exclusive":(event_day+timedelta(days=4,hours=2)).isoformat(),
      "duration_hours":2,"peak":27.1,"mean":24.8,"excess_above_relative_p90":10.4}]
    return {"schema_version":"1","days":days,"offset_days":offset,"start_date_utc":d["start_date_utc"],
     "end_date_utc_exclusive":d["end_date_utc_exclusive"],
     "pm25":{"hours_available":days*24,"hours_expected":days*24,"coverage_pct":100,
       "median":10.5,"p90":17.2,"maximum":29.5,"complete_days":days,
       "days_above_who_reference":sum(x["above_who_ambient_reference"] for x in daily),
       "daily":daily,"episodes":episodes},
     "diurnal":diurnal,"weekday":weekday,"weekday_hour_heatmap":heat,
     "associations":[{"sensor":name,"label":label,"paired_hours":days*24,"r":value}
       for name,label,value in [("VOC","VOC",.34),("CO","CO",-.08),("Humidity","Umidità",.27)]],
     "available_channels":[{"sensor":k,"hours":days*24} for k in NAMES]}

def context(days,offset=0):
    d=data(days,offset)
    start=datetime.fromisoformat(d["start_date_utc"]).replace(tzinfo=timezone.utc)
    count=min(72,days*24)
    base=int((start-START).total_seconds()/3600)
    paired=[{"time_utc":(start+timedelta(hours=i)).isoformat(),
       "indoor":series("PM25",base+i),
       "outdoor_model":round(8+2*math.sin(i*.14),1)} for i in range(count)]
    event=start+timedelta(days=2,hours=19)
    return {"schema_version":"1","timezone":"UTC","start_date_utc":d["start_date_utc"],"end_date_utc_exclusive":d["end_date_utc_exclusive"],
     "outdoor":{"configured":True,"last_sync_utc":(END-timedelta(hours=1)).isoformat(),"provider":"Open-Meteo / CAMS"},
     "comparison":{"paired_hours":count,"mean_indoor":mean([p["indoor"] for p in paired]),
       "mean_outdoor_model":mean([p["outdoor_model"] for p in paired]),"paired_hourly":paired},
     "activities":[{"id":"0123456789abcdef"*2,"activity":"cooking","label":"Cucina",
       "start_utc":event.isoformat(),"duration_minutes":45,
       "note":"Cena preparata in cucina (dato sintetico)","pm25_delta_two_hours_descriptive":3.4}]}

class Handler(BaseHTTPRequestHandler):
    def log_message(self,*args): pass
    def do_GET(self):
        q=urlparse(self.path)
        pages={"/":"dashboard.html","/pollution":"pollution.html","/context":"context.html"}
        try:
            days=int(parse_qs(q.query).get("days",[30])[0])
            offset=int(parse_qs(q.query).get("offset",[0])[0])
            if days not in (7,14,30) or not 0<=offset<=90: raise ValueError("range")
            if q.path in pages:
                html=(ROOT/pages[q.path]).read_text(encoding="utf-8")
                # Visible in every screenshot to avoid confusing mock measurements with real data.
                html=html.replace("<body>",'<body><div id="synthetic-badge" style="position:fixed;z-index:100000;right:8px;top:5px;padding:5px 7px;background:#ffdf97;color:#2e2317;border-radius:6px;font:700 10px system-ui;pointer-events:none">DATI SINTETICI · UX TEST</div>',1)
                out=html.encode("utf-8");ctype="text/html; charset=utf-8"
            elif q.path=="/api/dashboard":
                out=json.dumps(data(days,offset)).encode();ctype="application/json"
            elif q.path=="/api/pollution":
                out=json.dumps(pollution(days,offset)).encode();ctype="application/json"
            elif q.path=="/api/context":
                out=json.dumps(context(days,offset)).encode();ctype="application/json"
            else:
                self.send_error(404);return
            self.send_response(200);self.send_header("Content-Type",ctype)
            self.send_header("Content-Length",str(len(out)));self.send_header("Cache-Control","no-store")
            self.end_headers();self.wfile.write(out)
        except (ValueError, OSError) as exc:
            self.send_error(400)

if __name__=="__main__":
    server=ThreadingHTTPServer(("127.0.0.1",int(sys.argv[1]) if len(sys.argv)>1 else 18766),Handler)
    print("SYNTHETIC_SERVER_READY",flush=True)
    try:server.serve_forever()
    except KeyboardInterrupt:pass
    finally:server.server_close()
